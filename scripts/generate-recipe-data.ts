// Generate regional variants of each Indian base dish
function generateIndianRecipes(): Recipe[] {
  const regions: { name: string; cuisine: string }[] = [
    { name: 'Punjabi', cuisine: 'Punjabi' },
    { name: 'Bengali', cuisine: 'Bengali' },
    { name: 'Gujarati', cuisine: 'Gujarati' },
    { name: 'Maharashtrian', cuisine: 'Maharashtrian' },
    { name: 'Rajasthani', cuisine: 'Rajasthani' },
    { name: 'Kashmiri', cuisine: 'Kashmiri' },
    { name: 'Tamil', cuisine: 'Tamil' },
    { name: 'Kerala', cuisine: 'Kerala' },
    { name: 'Andhra', cuisine: 'Andhra' },
    { name: 'Hyderabadi', cuisine: 'Hyderabadi' },
    { name: 'Goan', cuisine: 'Goan' },
    { name: 'Odia', cuisine: 'Odia' },
    { name: 'Karnataka', cuisine: 'Karnataka' },
    { name: 'Bihari', cuisine: 'Bihari' },
    { name: 'Assamese', cuisine: 'Assamese' },
    { name: 'Uttar Pradeshi', cuisine: 'Uttar Pradeshi' },
    { name: 'Madhya Pradeshi', cuisine: 'Madhya Pradeshi' },
    { name: 'Haryanvi', cuisine: 'Haryanvi' },
    { name: 'Sindhi', cuisine: 'Sindhi' },
    { name: 'Chhattisgarhi', cuisine: 'Chhattisgarhi' },
  ]

  const result: Recipe[] = []
  for (const base of indianBases) {
    // First include the base recipe as-is
    result.push(base)
    // Then generate regional variants (skip the original region)
    for (const r of regions) {
      if (base.region === r.name) continue
      const variant: Recipe = {
        ...base,
        title: `${r.name} ${base.title}`,
        description: `${base.description} Prepared here in the ${r.name} style with regional spice adjustments.`,
        region: r.name,
        cuisine: r.cuisine,
        tags: [...(base.tags || []), r.name.toLowerCase()],
        steps: base.steps.map((s, idx) => idx === 0
          ? { ...s, instruction: `${r.name} style. ${s.instruction}` }
          : s
        ),
        caloriesPerServing: base.caloriesPerServing
          ? Math.round(base.caloriesPerServing * (1 + (r.name.length % 5) * 0.01))
          : undefined,
        cookTimeMin: base.cookTimeMin + (r.name.length % 3),
      }
      result.push(variant)
    }
  }

  // Dedupe by title
  const seen = new Set<string>()
  const unique: Recipe[] = []
  for (const r of result) {
    if (seen.has(r.title)) continue
    seen.add(r.title)
    unique.push(r)
  }

  // Pad or trim to exactly 500
  while (unique.length < 500) {
    const src = unique[unique.length % indianBases.length]
    unique.push({
      ...src,
      title: `${src.title} (Festive size ${unique.length})`,
      description: `${src.description} Festive-sized version ${unique.length}.`,
      servings: src.servings + 2,
    })
  }
  return unique.slice(0, 500)
}

