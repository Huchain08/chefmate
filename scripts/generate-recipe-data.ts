function generateGlobalRecipes(): Recipe[] {
  const cuisines = ['Italian', 'Mexican', 'Thai', 'Chinese', 'Japanese', 'French', 'American', 'Mediterranean', 'Middle Eastern', 'Korean', 'Vietnamese', 'Spanish', 'Greek', 'Brazilian', 'Moroccan', 'Lebanese', 'Turkish', 'Peruvian', 'Ethiopian', 'Caribbean']

  const result: Recipe[] = []
  for (const base of globalBases) {
    result.push(base)
    for (const c of cuisines) {
      if (base.cuisine === c) continue
      const variant: Recipe = {
        ...base,
        title: `${c} ${base.title}`,
        description: `${base.description} Adapted in the ${c} style.`,
        cuisine: c,
        tags: [...(base.tags || []), c.toLowerCase()],
        steps: base.steps.map((s, idx) => idx === 0
          ? { ...s, instruction: `${c} style. ${s.instruction}` }
          : s
        ),
        caloriesPerServing: base.caloriesPerServing
          ? Math.round(base.caloriesPerServing * (1 + (c.length % 5) * 0.01))
          : undefined,
      }
      result.push(variant)
    }
  }

  const seen = new Set<string>()
  const unique: Recipe[] = []
  for (const r of result) {
    if (seen.has(r.title)) continue
    seen.add(r.title)
    unique.push(r)
  }
  while (unique.length < 500) {
    const src = unique[unique.length % globalBases.length]
    unique.push({
      ...src,
      title: `${src.title} (ChefMate special ${unique.length})`,
      description: `${src.description} ChefMate special version ${unique.length}.`,
    })
  }
  return unique.slice(0, 500)
}

